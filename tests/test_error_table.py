"""The error table in the README and CLAIMS says what eval/results/nhanes_errors.json says (amendment 9).

It also checks the table against the pre-registered secondary measure (same PPV and counts) and that the
confusion matrix adds up. The JSON is regenerated by `python3 eval/nhanes/errors.py` (needs the raw NHANES files)."""
import json
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
E = json.loads((ROOT / "eval/results/nhanes_errors.json").read_text())
NH = json.loads((ROOT / "eval/results/nhanes.json").read_text())
S, A = E["strategies"], E["added_value_over_baseline"]
README = re.sub(r"\s+", " ", (ROOT / "README.md").read_text(encoding="utf-8"))
CLAIMS = re.sub(r"\s+", " ", (ROOT / "docs/CLAIMS.md").read_text(encoding="utf-8"))
COLS = ("engine", "baseline", "combined")


def pct(e):
    return f"{e['per_1000'] / 10:.1f} % ({e['ci95_lo'] / 10:.1f}–{e['ci95_hi'] / 10:.1f})"


def k(e):
    return f"{e['per_1000']:.1f} ({e['ci95_lo']:.1f}–{e['ci95_hi']:.1f})"


def nne(e):
    return f"{e['point']:.2f} ({e['ci95'][0]:.2f}–{e['ci95'][1]:.2f})"


@pytest.mark.parametrize("label,key,fmt", [
    ("Sensitivity", "sensitivity", pct), ("Specificity", "specificity", pct), ("PPV (order confirmed)", "ppv", pct),
    ("Missed per 1,000 people", "missed_per_1000", k), ("False alarms per 1,000 people", "false_alarms_per_1000", k),
    ("Orders per confirmed case", "number_needed_to_evaluate", nne),
])
def test_readme_row(label, key, fmt):
    row = f"| {label} | " + " | ".join(fmt(S[s][key]) for s in COLS) + " |"
    assert row in README, row


def test_readme_added_value_and_population():
    assert f"misses {pct(A['reference_positive_missed_by_baseline_per_1000_ref'])}" in README
    assert f"repeat for {pct(A['of_those_found_by_engine_per_1000'])}" in README
    assert f"{E['population_with_second_sample']:,} people with a second urine sample" in README
    assert "test-retest" in README and "not a fair contest" in README


def test_claims_row():
    row = next(line for line in CLAIMS.split("| ") if line.startswith("Error table"))
    e, b, c = S["engine"], S["baseline"], S["combined"]
    p1 = lambda x: f"{x['per_1000'] / 10:.1f} %"  # noqa: E731
    expected = [
        f"engine sensitivity {pct(e['sensitivity'])}", f"specificity {pct(e['specificity'])}", f"PPV {p1(e['ppv'])}",
        f"missed {e['missed_per_1000']['per_1000']:.1f} / false alarms {e['false_alarms_per_1000']['per_1000']:.1f} per 1,000",
        f"{e['number_needed_to_evaluate']['point']:.2f} orders per confirmed case",
        *[f"{p1(x['sensitivity'])} / {p1(x['specificity'])} / {p1(x['ppv'])}, "
          f"{x['missed_per_1000']['per_1000']:.1f} / {x['false_alarms_per_1000']['per_1000']:.1f}, "
          f"{x['number_needed_to_evaluate']['point']:.2f}" for x in (b, c)],
        f"misses {pct(A['reference_positive_missed_by_baseline_per_1000_ref'])}",
        f"repeat for {pct(A['of_those_found_by_engine_per_1000'])}",
        f"n = {E['population_with_second_sample']:,}", "same ACR ≥ 30 test",
    ]
    for claim in expected:
        assert claim in row, claim
    assert "tests/test_error_table.py" in CLAIMS


def test_committed_md_matches_json():
    import sys
    sys.path.insert(0, str(ROOT / "eval" / "nhanes"))
    from errors import render_md
    assert (ROOT / "eval/results/nhanes_errors.md").read_text(encoding="utf-8") == render_md(E)


def test_same_test_caveat_travels_with_the_numbers():
    assert any("test-retest" in x for x in E["not_measured"])
    assert "same ACR ≥ 30 test" in CLAIMS and "sensitivity and specificity here are mostly" in README


def test_matches_preregistered_secondary():
    sec = next(v for kk, v in NH["secondary"].items() if kk.startswith("repeat_orders_confirmed"))
    miss = next(v for kk, v in NH["secondary"].items() if kk.startswith("missed_by_single_test"))
    eng = S["engine"]
    assert eng["ppv"]["per_1000"] == sec["per_1000"] and eng["ppv"]["n"] == sec["n"]
    c = eng["counts_unweighted"]
    assert (c["tp"], c["tp"] + c["fp"], c["fn"], c["fn"] + c["tn"]) == (sec["events"], sec["n"], miss["events"], miss["n"])
    assert E["population_with_second_sample"] == NH["secondary"]["population_with_second_sample"]
    assert abs((1000 - eng["npv"]["per_1000"]) - miss["per_1000"]) <= 0.15


@pytest.mark.parametrize("s", COLS)
def test_confusion_matrix_adds_up(s):
    c = S[s]["counts_unweighted"]
    assert sum(c.values()) == E["population_with_second_sample"]
    assert c["tp"] + c["fn"] == E["reference_positive_unweighted"]
    assert S[s]["sensitivity"]["n"] == E["reference_positive_unweighted"]


@pytest.mark.skipif(not (ROOT / "eval/nhanes/raw/ALB_CR_F.xpt").exists(), reason="raw NHANES files not downloaded (CI)")
def test_committed_errors_are_current():
    import subprocess
    import sys
    before = (ROOT / "eval/results/nhanes_errors.json").read_text()
    subprocess.run([sys.executable, str(ROOT / "eval/nhanes/errors.py")], check=True, capture_output=True)
    assert (ROOT / "eval/results/nhanes_errors.json").read_text() == before
