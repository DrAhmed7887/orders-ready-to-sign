"""The workflow diagram says what the code and the committed results say.

- Population numbers come from eval/results/nhanes.json.
- The real trace comes from eval/results/nhanes_trace.json, and the steps it marks "Not tested" really did not run.
- Amparo's trace matches her synthetic record, the recorded model output and her order.
- Every file the diagram names exists.
The SVGs are regenerated by `node docs/diagram/build.mjs` (needs Chrome)."""
import json
import re
from datetime import date
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
NH = json.loads((ROOT / "eval/results/nhanes.json").read_text())
TR = json.loads((ROOT / "eval/results/nhanes_trace.json").read_text())
P = NH["primary"]["per_1000_adults_with_diabetes_or_hypertension"]
HIDDEN = next(v for k, v in P.items() if k.startswith("albuminuria_behind"))
CONFIRMED = next(v for k, v in NH["secondary"].items() if k.startswith("repeat_orders_confirmed"))
WIDE, TALL = "docs/workflow.svg", "docs/workflow_4x5.svg"
SPEC = (ROOT / "docs/diagram/build.mjs").read_text(encoding="utf-8")
ST, REAL = TR["steps_on_real_data"], TR["trace"]["egfr_60_or_more"]


def text_of(path):
    raw = (ROOT / path).read_text(encoding="utf-8")
    body = re.sub(r"<desc>.*?</desc>", " ", raw, flags=re.S)
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", body).replace("\u00a0", " ").replace("&amp;", "&"))


def has(text, claim):
    return re.search(r"(?<![\d.,])" + re.escape(claim), text) is not None


@pytest.mark.parametrize("path", [WIDE, TALL])
def test_population_number(path):
    assert has(text_of(path), f"{int(round(HIDDEN['per_1000']))} per 1,000")


def test_confirmation_rate_with_ci():
    ci = f"{round(CONFIRMED['ci95_lo'] / 10)}–{round(CONFIRMED['ci95_hi'] / 10)}"
    assert has(text_of(WIDE), f"{CONFIRMED['per_1000'] / 10:.1f} % (95 % CI {ci})")


@pytest.mark.parametrize("path", [WIDE, TALL])
def test_real_trace_matches_results(path):
    t = text_of(path)
    assert REAL["egfr"] >= 60 and REAL["engine_rule"] == "S1b" and REAL["second_sample_confirms"]
    for claim in [f"eGFR {REAL['egfr']} ", f"ACR {REAL['acr_first_mg_g']} ", f"ACR {REAL['acr_second_mg_g']} (≥ 30)",
                  f"median of {REAL['group_size']} like her"]:
        assert has(t, claim), claim
    assert "not signed" in t and "10 days later" in t and "ACR ≥ 30 on one visit" in t
    assert not re.search(r"10 days later[^✓]{0,40}✓", t), "no tick on the real second sample"


@pytest.mark.parametrize("path", [WIDE, TALL])
def test_untested_steps_really_did_not_run(path):
    assert ST["4_S1c"] == 0 and ST["orders_with_note_text"] == 0 and ST["4_rows_removed_from_list_any_reason"] == 0
    assert set(ST["extract_rows"]) == {"note", "nota_hallazgo", "pedido_pendiente", "drug_exposure"}
    assert not any(ST["extract_rows"].values())
    assert [k for k, n in ST["2_rules_fired"].items() if n] == ["S1b"]
    t = text_of(path)
    assert t.count("Not tested") == 2
    # The two "Not tested" lines belong to the note reader and the final rules, right after the real-data label.
    assert re.search(r"Note reader .*?(Real · NHANES|NHANES) Not tested: NHANES has no notes", t)
    assert re.search(r"Final rules .*?(Real · NHANES|NHANES) Not tested: no notes or orders", t)


@pytest.mark.skipif(not (ROOT / "eval/nhanes/raw/ALB_CR_F.xpt").exists(), reason="raw NHANES files not downloaded (CI)")
def test_committed_trace_is_current(tmp_path):
    import subprocess
    import sys
    before = (ROOT / "eval/results/nhanes_trace.json").read_text()
    subprocess.run([sys.executable, str(ROOT / "eval/nhanes/trace.py")], check=True, capture_output=True)
    assert (ROOT / "eval/results/nhanes_trace.json").read_text() == before


def months(a, b):
    return (b.year - a.year) * 12 + b.month - a.month


@pytest.mark.parametrize("path", [WIDE, TALL])
def test_amparo_trace_matches_her_record(path):
    sql = (ROOT / "data/synthetic/aguja/extracto.sql").read_text(encoding="utf-8")
    ref = date.fromisoformat(re.search(r"INSERT INTO extract_meta VALUES \(1, '([\d-]+)'", sql).group(1))
    assert "Trae informe de la mutua: CAC 110 mg/g el 12/09/2026." in sql
    first = json.loads((ROOT / "data/synthetic/aguja/salidas_qwen3-4b-instruct-2507.jsonl").read_text().splitlines()[0])
    assert first["salida"]["frase"] == 2 and first["salida"]["prueba"] == "CAC"
    order = next(o for o in json.loads((ROOT / "ui/pedidos_aguja.json").read_text())["pedidos"]
                 if o["id"] == "S1c-251-2026-09-12")
    assert order["hora_cita"] == "10:20" and "N18" in order["pedido"]
    assert "85 mg/g (laboratorio, 2026-01-10)" in order["motivo"]
    assert "FGe 68 (2026-09-20) · FGe 72 (2025-09-20)" in " ".join(f["dato"] for f in order["fuentes"])
    assert months(date(2026, 1, 10), ref) == 10 and months(date(2026, 1, 10), date(2026, 9, 12)) == 8
    t = text_of(path)
    for claim in ["Not repeated for 10 months", "8 months apart", "10:20", "eGFR 72 → 68", "ACR 85",
                  "“sentence 2”", "ACR 110, 12 Sep ✓", "consider a CKD code (N18)"]:
        assert claim in t, claim


def test_every_file_named_in_the_diagram_exists():
    names = re.findall(r"[\w/]+\.(?:py|html|sql)\b", SPEC)
    assert "ejecutar.py" in names and "verificar.py" in names
    for name in names:
        assert any(p.as_posix().endswith(name) for p in ROOT.rglob(Path(name).name)), name


@pytest.mark.parametrize("path", [WIDE, TALL, "docs/workflow.png", "docs/workflow_4x5.png"])
def test_outputs_committed(path):
    assert (ROOT / path).stat().st_size > 1000
