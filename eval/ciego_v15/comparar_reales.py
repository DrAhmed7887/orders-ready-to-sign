"""What the signed round-15 checks (V2-V7) change on the real published texts, finding by finding (descriptive).

    python3 eval/ciego_v15/comparar_reales.py   ->  eval/results/vuelta15_real_diff.md

Replays the committed recordings (no model run) through the round-14 checks (commit b83fa2c) and the working tree,
and lists every case whose ACCEPTED findings differ. These texts informed the rules (held-out 2 found E-14..E-19), so
this is not a test. The committed results files keep describing the checks they were reviewed with.
"""
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "eval" / "notas_reales"))
sys.path.insert(0, str(ROOT / "eval" / "ciego_v15"))

from notas.leer import LectorGrabado  # noqa: E402
from puntuar import ANTES, _load  # noqa: E402
from revisar import CONJUNTOS, HERE, HOY, NOTE_DATE  # noqa: E402

OUT = ROOT / "eval" / "results" / "vuelta15_real_diff.md"


def accepted(v, text, salida):
    return [(r["etiqueta"], r.get("prueba"), r.get("valor"), r.get("unidad"), r.get("fecha_cita"), r.get("motivo_rechazo"))
            for r in v.verificar(text, NOTE_DATE, salida, HOY) if r["verificada"] == 1]


def main() -> int:
    if not (HERE / "raw").exists():
        raise SystemExit("real texts not downloaded: run eval/notas_reales/fetch.py and fetch_livingner.py")
    with tempfile.TemporaryDirectory() as d:
        old_p = Path(d) / "v14.py"
        old_p.write_bytes(subprocess.run(["git", "show", f"{ANTES}:notas/verificar.py"], cwd=ROOT, check=True,
                                         capture_output=True).stdout)
        old, new = _load(old_p, "v14"), _load(ROOT / "notas" / "verificar.py", "v15")
        md = ["# Round 15 (signed V2-V7) on the real texts: every changed finding", "",
              "Generated by `python3 eval/ciego_v15/comparar_reales.py`. Recorded model outputs, no new run. "
              "Descriptive: these texts informed the rules.", ""]
        for conjunto in ("dev", "heldout", "heldout2"):
            muestra_p, grabadas_p, _, _ = CONJUNTOS[conjunto]
            lector = LectorGrabado(grabadas_p)
            cases = json.loads(muestra_p.read_text(encoding="utf-8"))["cases"]
            n_old = n_new = 0
            rows = []
            for c in cases:
                text = (HERE / "raw" / f"{c['id']}.txt").read_text(encoding="utf-8")
                salida = lector(text)
                a, b = accepted(old, text, salida), accepted(new, text, salida)
                n_old, n_new = n_old + len(a), n_new + len(b)
                if a != b:
                    rows.append(f"- `{c['id']}`: round 14 {a or 'nothing'} → signed {b or 'nothing'}")
            md += [f"## {conjunto} ({len(cases)} notes): accepted findings {n_old} → {n_new}", "", *(rows or ["- no change"]), ""]
    OUT.write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
